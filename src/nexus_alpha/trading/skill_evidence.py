"""Direction-skill evidence for gate 3 of the risk engine (audit 9, finding A-101; decision D-057).

Gate 3 used to rest on one block: a horizon was tradable when the frozen bundle's up-vs-down AUROC on the 2017-18
validation block had a 95% interval above 0.5 (`direction_skill` in `bundle_meta.json`, kept as frozen). Recomputed the
same way on the 2020-2022 development test block (`scripts/verify/direction_replication.py`), that skill did not
replicate at any horizon where it had been validated, for v1.1 or v2.

The gate now requires both:
1. **validated**: the frozen 2017-18 flag (unchanged; the forward-test logs keep recording it), and
2. **replicated**: the same statistic on 2020-2022 with its interval above 0.5 (the table below, generated by the
   script and checked against `reports/verification/direction_replication_2020_2022.json` by the tests).

Using the test years here can only close a gate, never open one, so it cannot flatter a result. A horizon re-opens only
with forward evidence: once the forward test has 120 matured sessions for a model, its forward up-vs-down AUROC
interval must lie above 0.5 (D-057); that replaces the 2020-2022 row for that model and horizon.

The frozen models, their bundles, the forward-test logs and the sealed scorer are untouched: this module is used only
by the dashboard's planner calls (`inference/pipeline.py`, the Trade Desk).
"""
