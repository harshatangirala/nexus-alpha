"""Compile reports/RESULTS.md from saved experiment artifacts only (no number is typed by hand).

Run: .venv/Scripts/python -I scripts/report/make_results.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
H = ["1D", "2D", "5D", "10D", "20D", "1M"]


def latest(prefix):
    for r in sorted((ROOT / "experiments").glob(f"*_{prefix}_*"), reverse=True):
        if not (r / "manifest.json").exists():
            continue
        m = json.loads((r / "manifest.json").read_text(encoding="utf-8"))
        if m.get("status") == "COMPLETED" and (r / "metrics.json").exists():
            return r.name, json.loads((r / "metrics.json").read_text(encoding="utf-8"))
    return None, None


def f(x, d=4):
    return "n/a" if x is None or x != x else f"{x:.{d}f}"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(out)


def main() -> int:
    L = ["# NEXUS Alpha results (compiled from artifacts)", "",
         "Generated by `scripts/report/make_results.py` from `experiments/*/metrics.json` and `reports/*`. The 2020-2022 test "
         "block is a historical diagnostic (already read by TriFrame for its own targets). Log loss: lower is better; the "
         "class prior is the no-skill reference.", ""]
    rid, m = latest("e01_structured_baselines")
    if m:
        L += [f"## E01 structured baselines (`{rid}`), test 2020-2022", ""]
        rows = []
        for h in H:
            for name in ("prior", "momentum_lr", "lgbm_structured", "lgbm_x33", "lgbm_struct_x33", "lgbm_struct_x33_mkt"):
                r = m[h]["test"][name]
                d = r.get("dlogloss_vs_prior") or {}
                rows.append({"horizon": h, "model": name, "log loss": f(r["log_loss"]),
                             "gain vs prior [95% CI]": "" if not d else f"{-d['estimate']:+.4f} [{-d['ci95'][1]:+.4f}, {-d['ci95'][0]:+.4f}]",
                             "AUROC up vs down": f(r.get("auroc_up_vs_down"), 3), "AUROC sideways": f(r.get("auroc_SIDEWAYS"), 3),
                             "macro-F1": f(r["macro_f1"], 3), "ECE": f(r["ece_top"], 3)})
        L += [md_table(pd.DataFrame(rows)), ""]
    rid, m = latest("e02_cv_branch")
    if m:
        L += [f"## E02 chart branch (`{rid}`): mean validation log loss over six horizons (images only, linear heads)", ""]
        names = sorted({n for h in H for n in m[h]["valid"]})
        rows = [{"model": n, "valid mean log loss": f(sum(m[h]["valid"][n]["log_loss"] for h in H) / 6),
                 "test mean log loss": f(sum(m[h]["test"][n]["log_loss"] for h in H) / 6),
                 "test AUROC up vs down (5D)": f(m["5D"]["test"][n].get("auroc_up_vs_down"), 3)} for n in names]
        L += [md_table(pd.DataFrame(rows).sort_values("valid mean log loss")), ""]
    rid, m = latest("e03_fusion")
    if m:
        L += [f"## E03 multimodal fusion (`{rid}`)", "", f"Selected variant: **{m['bundle']['variant']}** (lowest validation "
              f"mean log loss). Calibration per horizon: {m['bundle']['calibration']}.", ""]
        rows = []
        for n, v in m.items():
            if isinstance(v, dict) and "valid" in v and "test_raw" in v:
                rows.append({"model": n, "modalities": "+".join(v["modalities"]), "valid": f(v["valid"]["mean_log_loss"], 5),
                             "test (uncalibrated)": f(v["test_raw"]["mean_log_loss"], 5),
                             "test AUROC up/down 5D": f(v["test_raw"]["5D"].get("auroc_up_vs_down"), 3),
                             "test AUROC sideways 5D": f(v["test_raw"]["5D"].get("auroc_SIDEWAYS"), 3)})
        L += [md_table(pd.DataFrame(rows).sort_values("valid")), ""]
        sc = m["selected_calibrated"]
        L += ["Selected model after calibration, test block:", "",
              md_table(pd.DataFrame([{"horizon": h, "log loss": f(sc["test"][h]["log_loss"]), "ECE": f(sc["test"][h]["ece_top"], 3),
                                      "accuracy": f(sc["test"][h]["accuracy"], 3), "balanced acc.": f(sc["test"][h]["balanced_accuracy"], 3),
                                      "macro-F1": f(sc["test"][h]["macro_f1"], 3), "AUROC up/down": f(sc["test"][h].get("auroc_up_vs_down"), 3),
                                      "n": sc["test"][h]["n"]} for h in H])), ""]
        hy = m["hypotheses"]
        L += ["### Registered hypotheses (paired month-block bootstrap, test block; positive = improvement)", "",
              md_table(pd.DataFrame([{"hypothesis": k, "estimate": f(v["estimate"], 5), "95% CI": f"[{v['ci95'][0]:+.5f}, {v['ci95'][1]:+.5f}]",
                                      "one-sided p": f(v["p_one_sided"], 3), "Holm p": f(hy["holm"][k]["p_holm"], 3),
                                      "supported at 5%": hy["holm"][k]["reject_at_alpha"] and v["estimate"] > 0}
                                     for k, v in hy["tests"].items()])), "",
              f"H1 reference single view: {hy['single_view_reference']}; H2 rows (news present or SEC covered): {hy['h2_rows']}.", ""]
        L += ["### Missing-modality stress test (selected model, test block)", "",
              md_table(pd.DataFrame([{"masked": k, "mean log loss": f(v["mean_log_loss"], 5), "change vs full": f(v["delta_vs_full"], 5)}
                                     for k, v in m["missing_modality_stress"].items()])), ""]
        ds = m["bundle"]["direction_skill"]
        L += ["### Direction-skill gate (validation 2017-2018, calibrated selected model)", "",
              md_table(pd.DataFrame([{"horizon": h, "AUROC up vs down": f(v["valid_up_vs_down_auroc"], 3),
                                      "95% CI": f"[{v['ci95'][0]:.3f}, {v['ci95'][1]:.3f}]", "validated": v["validated"]} for h, v in ds.items()])), ""]
    rid, m = latest("e05_walk_forward")
    if m:
        L += [f"## E05 walk-forward 2008-2022 (`{rid}`), LightGBM structured model", "",
              md_table(pd.DataFrame([{"horizon": h, "mean log-loss gain vs prior": f(v["mean_d_logloss"]),
                                      "years improved (of 15)": v["years_improved"], "t (years)": f(v["t_years"], 2),
                                      "mean AUROC up vs down": f(v["mean_auc_up_vs_down"], 3),
                                      "years AUROC > 0.5": v["years_up_vs_down_above_0.5"], "p (AUROC = 0.5)": f(v["p_up_vs_down"], 3),
                                      "mean AUROC sideways": f(v["mean_auc_sideways"], 3)} for h, v in m["summary"].items()])), ""]
        fm = ROOT / "reports" / "walk_forward" / "e05_fold_metrics.csv"
        if fm.exists():
            d = pd.read_csv(fm)
            piv = d.pivot(index="test_year", columns="horizon", values="auc_up_vs_down").round(3)
            L += ["Up-vs-down AUROC by test year:", "", md_table(piv.reset_index()), ""]
    bt = ROOT / "reports" / "backtest" / "e04_backtest.json"
    if bt.exists():
        b = json.loads(bt.read_text(encoding="utf-8"))
        L += ["## E04 economic backtest, test 2020-2022 (thresholds frozen on 2017-2018)", "",
              md_table(pd.DataFrame([{"policy": k, "trades": v.get("trades", 0), "Sharpe": f(v["sharpe"], 2),
                                      "Sharpe 95% CI": "[" + ", ".join(f(x, 2) for x in v["sharpe_ci95_month_blocks"]) + "]",
                                      "CAGR": f(v["cagr"], 3), "max DD": f(v["max_drawdown"], 3), "win rate": f(v.get("win_rate"), 3),
                                      "expectancy R": f(v.get("expectancy_R"), 3), "DSR": f((v.get("deflated_sharpe") or {}).get("dsr"), 3)}
                                     for k, v in b["test_final"].items()])), "",
              f"Equal-weight survivor benchmark, test: Sharpe {f(b['benchmark_ew_survivors']['test']['sharpe'], 2)}, CAGR "
              f"{f(b['benchmark_ew_survivors']['test']['cagr'], 3)}, max drawdown {f(b['benchmark_ew_survivors']['test']['max_drawdown'], 3)}. "
              f"PBO over {b['pbo'].get('n_configs')} configurations: {f(b['pbo'].get('pbo'), 3)}. Frozen thresholds: {b['frozen_thresholds']}.", ""]
    rid, m = latest("e06_optimization")
    if m:
        L += [f"## E06 fusion optimisation study (`{rid}`, post-registration, selection on validation)", "",
              md_table(pd.DataFrame([{"run": n, "lr": v.get("lr"), "d_model": v.get("d_model"), "dropout": v.get("dropout"),
                                      "wd": v.get("weight_decay"), "seed": v.get("seed"), "epochs": v.get("epochs"),
                                      "best epoch": v.get("best_epoch"), "valid": f(v["valid"], 5), "test": f(v["test"], 5)}
                                     for n, v in m.items() if isinstance(v, dict) and "history" in v])), "",
              f"Seed ensembles: fusion valid {f(m['best_seed_ensemble']['valid'], 5)} / test {f(m['best_seed_ensemble']['test'], 5)}; "
              f"numbers-only valid {f(m['num_seed_ensemble']['valid'], 5)} / test {f(m['num_seed_ensemble']['test'], 5)}. "
              f"Seed spread (best config): valid {f(m['seed_spread']['valid_mean'], 5)} ± {f(m['seed_spread']['valid_sd'], 5)}, "
              f"test {f(m['seed_spread']['test_mean'], 5)} ± {f(m['seed_spread']['test_sd'], 5)}. Landscape: centre "
              f"{f(m['landscape']['center_valid_ce'], 5)}, lowest grid point {f(m['landscape']['min_on_grid'], 5)} at "
              f"{m['landscape']['argmin_on_grid']}.", ""]
    rid, m = latest("e07_lgbm_tuning")
    if m:
        L += [f"## E07 LightGBM tuning (`{rid}`)", "", f"Best of {m['n_trials']} TPE trials: {m['best_params']}; mean validation log loss "
              f"(1D/5D/20D) {f(m['best_value'], 5)} vs default {f(m['default_value'], 5)}.", "",
              md_table(pd.DataFrame([{"horizon": h, "best iteration": m["curves"][h]["best_iteration_inner"],
                                      "tuned valid": f(m["scores"]["tuned"][h]["valid"], 5), "tuned test": f(m["scores"]["tuned"][h]["test"], 5),
                                      "refit test": f(m["scores"]["refit"][h]["test"], 5)} for h in H])), ""]
    p9 = ROOT / "reports" / "e09_convexity_certificate.json"
    if p9.exists():
        c = json.loads(p9.read_text(encoding="utf-8"))
        L += ["## E09 convexity certificate (multinomial logistic, numeric features)", "",
              md_table(pd.DataFrame([{"horizon": h, "certified": v["certified_global_minimum"], "objective spread": f"{v['objective_range']:.1e}",
                                      "param spread": f"{v['max_param_distance_between_starts']:.1e}", "grad norm": f"{v['gradient_norm_at_solution']:.1e}",
                                      "Hessian min eig": f"{v['hessian_min_eigenvalue']:.1e}", "valid log loss": f(v["valid_log_loss"], 5)}
                                     for h, v in c.items()])), ""]
    rid, m = latest("e08_final_model")
    if m:
        L += [f"## E08 final model (`{rid}`)", "", f"Selected on validation among {m['n_candidates']} candidates: **{m['selected']}**. "
              f"Calibration on the test years (mean log loss): {m['calibration_compare_test']}.", "",
              md_table(pd.DataFrame([{"horizon": h, "log loss": f(r["log_loss"]), "gain vs prior [95% CI]":
                                      f"{r['gain_vs_prior']['estimate']:+.4f} [{r['gain_vs_prior']['ci95'][0]:+.4f}, {r['gain_vs_prior']['ci95'][1]:+.4f}]",
                                      "gain vs E03": f"{r['gain_vs_e03']['estimate']:+.4f} [{r['gain_vs_e03']['ci95'][0]:+.4f}, {r['gain_vs_e03']['ci95'][1]:+.4f}]",
                                      "AUROC up/down [95% CI]": f"{r['auroc_up_down_ci']['estimate']:.3f} [{r['auroc_up_down_ci']['ci95'][0]:.3f}, {r['auroc_up_down_ci']['ci95'][1]:.3f}]",
                                      "AUROC sideways": f(r.get("auroc_SIDEWAYS"), 3), "ECE": f(r["ece_top"], 3), "accuracy": f(r["accuracy"], 3),
                                      "balanced acc.": f(r["balanced_accuracy"], 3), "macro-F1": f(r["macro_f1"], 3)}
                                     for h, r in m["final"]["by_horizon"].items()])), ""]
    bt = ROOT / "reports" / "backtest" / "e04_backtest_v1.1.json"
    if bt.exists():
        b = json.loads(bt.read_text(encoding="utf-8"))
        L += ["## E04 v1.1 backtest (audit fixes A-01, A-02, A-04, A-06; final model), test 2020-2022", "",
              md_table(pd.DataFrame([{"policy": k, "trades": v.get("trades", 0), "Sharpe": f(v["sharpe"], 2),
                                      "Sharpe 95% CI": "[" + ", ".join(f(x, 2) for x in v["sharpe_ci95_month_blocks"]) + "]",
                                      "CAGR": f(v["cagr"], 3), "max DD": f(v["max_drawdown"], 3), "expectancy R": f(v.get("expectancy_R"), 3),
                                      "DSR": f((v.get("deflated_sharpe") or {}).get("dsr"), 3)} for k, v in b["test_final"].items() if k.endswith("|base")])), "",
              f"Benchmark Sharpe {f(b['benchmark_ew_survivors']['test']['sharpe'], 2)}; PBO {f(b['pbo'].get('pbo'), 3)}; frozen thresholds {b['frozen_thresholds']}.", ""]
    rid10, m10 = latest("e10_controls")
    if m10:
        rows10 = [{"horizon": h, "control": k, "valid_LL_minus_prior": v["valid"]["log_loss"] - v["valid"]["prior_log_loss"],
                   "test_LL_minus_prior": v["test"]["log_loss"] - v["test"]["prior_log_loss"], "trees": v["test"]["best_iteration"]}
                  for h, d in m10.items() for k, v in d.items()]
        L += ["## E10 controls (placebo and planted-leak canary; log loss minus class prior, negative = better)", "",
              md_table(pd.DataFrame(rows10).round(4)), ""]
    rag = ROOT / "reports" / "rag" / "rag_eval.json"
    if rag.exists():
        e = json.loads(rag.read_text(encoding="utf-8"))
        L += ["## RAG retrieval evaluation", "", md_table(pd.DataFrame(e["book"]).T.round(3).reset_index()), "",
              md_table(pd.DataFrame(e["rule"]).T.round(3).reset_index()), ""]
    (ROOT / "reports" / "RESULTS.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote reports/RESULTS.md", len(L), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
