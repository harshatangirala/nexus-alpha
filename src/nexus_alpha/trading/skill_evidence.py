def model_of_bundle(bundle_id: str | None) -> str | None:
    return BUNDLES.get(str(bundle_id)) if bundle_id else None


def replication(model: str | None, horizon: str) -> tuple[float, float, float] | None:
    return REPLICATION.get(model or "", {}).get(horizon)


def replicated(model: str | None, horizon: str) -> bool | None:
    rep = replication(model, horizon)
    return None if rep is None else bool(rep[1] > 0.5)


def direction_gate(model: str | None, horizon: str, validated: bool) -> tuple[bool, str | None]:
    """(open, reason if closed). Open only if the 2017-18 flag is set AND the 2020-2022 interval lies above 0.5."""
    rep = replication(model, horizon)
    if not validated:
        if rep is not None:
            return False, (f"no validated directional skill at this horizon (2017-18 interval includes 0.5; "
                           f"2020-22 up-vs-down AUROC {rep[0]:.3f} [{rep[1]:.3f}, {rep[2]:.3f}])")
        return False, "no validated directional skill at this horizon (validation up-vs-down AUROC interval includes 0.5)"
    if rep is None:
        return False, (f"direction skill validated on 2017-18 but never checked out of sample for {model} {horizon}: "
                       "gate closed until it is (D-057)")
    if rep[1] <= 0.5:
        return False, (f"direction skill validated on 2017-18 did not replicate on 2020-22 (up-vs-down AUROC "
                       f"{rep[0]:.3f} [{rep[1]:.3f}, {rep[2]:.3f}] includes 0.5): gate closed until the forward test "
                       "shows it (D-057)")
    return True, None
